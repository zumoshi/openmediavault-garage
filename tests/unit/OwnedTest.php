<?php

declare(strict_types=1);

use PHPUnit\Framework\TestCase;

use function OMV\Garage\aclGrants;
use function OMV\Garage\orphans;

final class OwnedTest extends TestCase
{
    private const RENDERED = "# This file is auto-generated by openmediavault (https://www.openmediavault.org)\n"
        . "# WARNING: Do not edit this file, your changes will get lost.\n"
        . "# Managed by openmediavault-garage. Do not edit.\n\n"
        . "metadata_dir = \"/srv/disk/a/meta\"\n";
    private const HANDMADE = "metadata_dir = \"/var/lib/garage/mine/meta\"\n";

    private static function model(array $shares): array
    {
        return ["shares" => $shares];
    }

    public function testOrphansAreRenderedTomlsOfInstancesNotEnabled(): void
    {
        self::assertSame(["gone"], orphans([
            "alpha" => self::RENDERED,
            "gone" => self::RENDERED,
            "mine" => self::HANDMADE,
        ], ["alpha"]));
    }

    public function testATomlThatOnlyMentionsTheMarkerIsNotOurs(): void
    {
        self::assertSame([], orphans([
            "mine" => "# copied from # Managed by openmediavault-garage.\n",
        ], []));
    }

    public function testAppliedGrantsAreRecordedBeforeTheyAreMade(): void
    {
        $acls = aclGrants(["/srv/old/"],
            [self::model(["/srv/a/" => "--x", "/srv/b/" => "rwx"])]);

        self::assertSame(["/srv/a/", "/srv/b/", "/srv/old/"], $acls["granted"]);
    }

    public function testOnlyRecordedFoldersNoInstanceUsesAreRevoked(): void
    {
        $acls = aclGrants(["/srv/a/", "/srv/old/"],
            [self::model(["/srv/a/" => "--x"]), self::model(["/srv/b/" => "rwx"])]);

        self::assertSame(["/srv/old/"], $acls["revoke"]);
        self::assertSame(["/srv/a/", "/srv/b/"], $acls["kept"]);
    }

    public function testNothingIsRevokedWhileAnInstanceCannotRender(): void
    {
        $acls = aclGrants(["/srv/a/", "/srv/old/"],
            [self::model(["/srv/a/" => "--x"]), null]);

        self::assertSame([], $acls["revoke"]);
        self::assertSame(["/srv/a/", "/srv/old/"], $acls["kept"]);
    }
}
